def scope_rows(con, exclude):
    q = (f"SELECT d.id, d.sha, d.qname, d.stmt, d.doc FROM decl_v d JOIN file f ON f.id = d.file_id "
         f"JOIN corpus c ON c.id = f.corpus_id"
         + (f" WHERE c.label NOT IN ({','.join('?' * len(exclude))})" if exclude else "") + " ORDER BY d.id")
    return con.execute(q, exclude)


def cmd_embed_export(a):
    import gzip
    import numpy as np
    con = open_db()
    exclude = a.exclude.split(",") if a.exclude else []
    seen, shas, ids = set(), [], []
    with gzip.open(a.out, "wt", encoding="utf-8", compresslevel=6) as fh:
        for did, sha, qname, stmt, doc in scope_rows(con, exclude):
            if sha in seen:
                continue
            seen.add(sha)
            shas.append(int(sha, 16))
            ids.append(did)
            fh.write(f"{sha}\t{embed_text(qname, stmt, doc)}\n")
    np.save(a.out + ".sha.npy", np.array(shas, dtype=np.uint64))
    np.save(a.out + ".ids.npy", np.array(ids, dtype=np.int64))
    print(f"-- {len(shas)} distinct texts (excluding {exclude or 'nothing'}) -> {a.out}", file=sys.stderr)


