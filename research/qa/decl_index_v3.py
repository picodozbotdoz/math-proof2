def load_enrich():
    rows = []
    if os.path.exists(ENRICH):
        with open(ENRICH, encoding="utf-8") as fh:
            for line in fh:
                if line.startswith("#") or not line.strip():
                    continue
                p = line.rstrip("\n").split("\t")
                if len(p) == len(ENRICH_COLS):
                    rows.append(dict(zip(ENRICH_COLS, p)))
                else:
                    print(f"WARN: malformed enrichment row skipped: {line.strip()[:120]}", file=sys.stderr)
    return rows


ENRICH_HEADER = """\
# decl-enrich-v3.tsv — curated enrichment overlay for decl-index-v3 (tracked).
# Adds clues to declarations whose own names are poor or uncommon; never edits a declaration.
# Edit with `python3 research/qa/decl_index_v3.py enrich add CORPUS QNAME TYPE TEXT --by WHO`
# (validates the declaration and records its sha), or by hand keeping 7 TAB-separated columns.
# A row applies to every v3 row with the same (corpus, qname); it survives index rebuilds.
# columns: corpus  qname  type  text  added_by  date  stmt_sha
#   type: alias (a better or more common name) | keyword (search terms) |
#         description (one plain sentence) | see-also (corpus:qname of a related declaration)
#   stmt_sha: v3 sha(s) of the declaration when the clue was written; `enrich check` reports
#             STALE (declaration text changed since) and DANGLING (declaration gone).
"""


def shas_for(con, corpus, qname):
    return {r[5] for r in name_lookup(con, qname, corpus=corpus, by="qname")}


def corpus_drift(check_dirty):
    """Per corpus: (label, manifest rev, current rev, dirty .lean count or None)."""
    with open(os.path.join(INDEX_DIR, MANIFEST_NAME), encoding="utf-8") as fh:
        m = json.load(fh)
    rows = []
    for c in m["corpora"]:
        cur = git_info(c["root"])["rev"] if os.path.isdir(c["root"]) else None
        dirty = None
        if check_dirty and cur:
            st = subprocess.run(["git", "-C", c["root"], "status", "--porcelain", "--", "."],
                                capture_output=True, text=True).stdout
            dirty = sum(1 for line in st.splitlines() if line.endswith(".lean"))
        rows.append((c["label"], c["rev"], cur, dirty))
    return m, rows


def cmd_status(a):
    m, rows = corpus_drift(check_dirty=True)
    present = os.path.exists(db_path())
    print(f"{m['index']} {m['extractor']} ({m.get('words')}) built {m['built_utc']}: {m['rows']} rows, "
          f"{DB_NAME} {'present' if present else 'MISSING (run build)'}")
    stale = 0
    for label, was, cur, dirty in rows:
        ok = cur == was and not dirty
        stale += not ok
        print(f"{'SAME' if ok else 'CHANGED':8} {label:24} built {str(was)[:10]}  now {str(cur)[:10]}"
              f"  dirty .lean: {dirty}")
    if a.verify and present:
        good = sha256_file(db_path()) == m["db_sha256"]
        stale += not good
        print(f"db sha256 {'matches' if good else 'DIFFERS from'} the manifest")
    print(f"enrichment: {len(load_enrich())} clues in {os.path.relpath(ENRICH, os.getcwd())}")
    if stale:
        print("-- STALE: rebuild (`build`), then `enrich check`", file=sys.stderr)
    sys.exit(1 if stale or not present else 0)


def print_row(row, tag, clues):
    corpus, path, line, kind, qname, _ = row
    print(f"{corpus}\t{path}:{line}\t{kind}\t{qname}\t[{tag}]")
    for c in clues.get((corpus, qname), []):
        print(f"\t  clue {c}")


def cmd_find(a):
    con = open_db()
    changed = [label for label, was, cur, _ in corpus_drift(check_dirty=False)[1] if cur != was]
    if changed:
        print(f"WARN: index is stale for {', '.join(changed)} (corpus moved since build) — "
              f"rebuild with `build`", file=sys.stderr)
    corpora = a.corpus.split(",") if a.corpus else []
    cfilter = f" AND c.label IN ({','.join('?' * len(corpora))})" if corpora else ""
    clues_by_key = {}
    enrich = load_enrich()
    for r in enrich:
        clues_by_key.setdefault((r["corpus"], r["qname"]), []).append(f'{r["type"]}: {r["text"]}')
    if a.semantic or a.like:
        semantic_find(a, con, corpora, clues_by_key, enrich)
        return
    if a.exact:
        name = " ".join(a.terms)
        rows = [r for r in name_lookup(con, name) if not corpora or r[0] in corpora][:a.limit]
        for row in rows:
            print_row(row, "exact", clues_by_key)
        print(f"-- {len(rows)} exact hits", file=sys.stderr)
        sys.exit(0 if rows else 1)
    qwords = tokens(" ".join(a.terms))
    if not qwords:
        sys.exit("no searchable words in the query")
    raw = " ".join(a.terms).lower()
    qwords = [w for w in qwords if w not in QUERY_STOPWORDS] or qwords
    shown, seen = 0, set()
    # 1. curated clues first: every query word among the clue's words, or a raw substring hit
    for r in enrich:
        cw = set(tokens(r["text"]))
        if (all(w in cw for w in qwords) or raw in r["text"].lower()) and (not corpora or r["corpus"] in corpora):
            for row in name_lookup(con, r["qname"], corpus=r["corpus"], by="qname"):
                key = (row[0], row[1], row[2], row[4])
                if key not in seen and shown < a.limit:
                    seen.add(key)
                    print_row(row, "via clue", clues_by_key)
                    shown += 1
    # 2. BM25-ranked full-text match over name / statement / docstring words (porter-stemmed,
    #    so finite/finitely/finiteness and zero/zeros match). All words must match unless
    #    --any; if no row has all of them, fall back to any-word matching, ranked by BM25.
    def fts_expr(sep):
        e = sep.join(f'"{w}"' for w in qwords)
        return f"name_words : ({e})" if a.names else e

    def count(e):
        return con.execute("SELECT count(*) FROM decl_fts WHERE decl_fts MATCH ?", (e,)).fetchone()[0]
    mode = "any word" if a.any else "all words"
    expr = fts_expr(" OR " if a.any else " ")
    total = count(expr)
    if total == 0 and not a.any and len(qwords) > 1:
        mode, expr = "any word (no row has all words)", fts_expr(" OR ")
        total = count(expr)
    rows = con.execute(
        f"SELECT c.label, f.path, d.line, d.kind, d.qname, d.sha, {BM25} AS s FROM decl_fts "
        f"JOIN decl_v d ON d.id = decl_fts.rowid JOIN file f ON f.id = d.file_id "
        f"JOIN corpus c ON c.id = f.corpus_id WHERE decl_fts MATCH ?{cfilter} ORDER BY s LIMIT ?",
        (expr, *corpora, a.limit + len(seen))).fetchall()
    for row in rows:
        key = (row[0], row[1], row[2], row[4])
        if key in seen or shown >= a.limit:
            continue
        seen.add(key)
        print_row(row[:6], f"bm25 {row[6]:.1f}", clues_by_key)
        shown += 1
    print(f"-- {total} full-text matches on {mode} [{' '.join(qwords)}]"
          f"{' (corpus filter applied to the ranked list)' if corpora else ''}; showing {shown}",
          file=sys.stderr)


def cmd_enrich_add(a):
    if a.type not in ENRICH_TYPES:
        sys.exit(f"type must be one of {ENRICH_TYPES}")
    if any(c in a.text for c in "\t\n") or not a.text.strip():
        sys.exit("text must be non-empty, without TAB or newline")
    con = open_db()
    target = None
    if a.type == "see-also":
        if ":" not in a.text:
            sys.exit("see-also text must be CORPUS:QNAME")
        target = tuple(a.text.split(":", 1))
    shas = {(a.corpus, a.qname): shas_for(con, a.corpus, a.qname)}
    if target:
        shas[target] = shas_for(con, *target)
    for key, s in shas.items():
        if not s:
            sys.exit(f"no v3 declaration with corpus={key[0]!r} qname={key[1]!r} (use `find` to get the qname)")
    existing = {(r["corpus"], r["qname"], r["type"], r["text"]) for r in load_enrich()}
    today = datetime.date.today().isoformat()
    rows = [(a.corpus, a.qname, a.type, a.text, ",".join(sorted(shas[(a.corpus, a.qname)])))]
    if target and a.both:
        rows.append((target[0], target[1], "see-also", f"{a.corpus}:{a.qname}", ",".join(sorted(shas[target]))))
    new = not os.path.exists(ENRICH)
    with open(ENRICH, "a", encoding="utf-8") as fh:
        if new:
            fh.write(ENRICH_HEADER)
        for corpus, qname, typ, text, sha in rows:
            if (corpus, qname, typ, text) in existing:
                print(f"skip (already present): {corpus} {qname} {typ}: {text}", file=sys.stderr)
                continue
            fh.write("\t".join((corpus, qname, typ, text, a.by, today, sha)) + "\n")
            print(f"added: {corpus} {qname} {typ}: {text}", file=sys.stderr)


def cmd_enrich_check(a):
    con = open_db()
    clues = load_enrich()
    cur = {}

    def get(key):
        if key not in cur:
            cur[key] = shas_for(con, *key)
        return cur[key]
    bad = 0
    for r in clues:
        key = (r["corpus"], r["qname"])
        status = "OK"
        if not get(key):
            status = "DANGLING"
        elif not (set(r["stmt_sha"].split(",")) & get(key)):
            status = "STALE"
        if status == "OK" and r["type"] == "see-also" and ":" in r["text"] \
                and not get(tuple(r["text"].split(":", 1))):
            status = "DANGLING-TARGET"
        bad += status != "OK"
        print(f"{status}\t{r['corpus']}\t{r['qname']}\t{r['type']}: {r['text']}")
    print(f"-- {len(clues)} clues, {bad} need attention", file=sys.stderr)
    sys.exit(1 if bad else 0)


