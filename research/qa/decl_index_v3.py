def words(text, ascii_ops=True):
    if not text:
        return ""
    for s, w in _MULTI:
        if s in text:
            text = text.replace(s, w)
    text = _SPLIT_RE.sub(" ", text.translate(_SYMBOL_TABLE if ascii_ops else _SYMBOL_TABLE_UNI))
    return " ".join(_CAMEL_RE.sub(" ", text).lower().split())


