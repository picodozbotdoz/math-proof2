#!/usr/bin/env python3
"""decl_index_v3.py — decl-index-v3: cross-corpus Lean declaration index with statement
text, plus a curated enrichment overlay. Successor of decl-index v1/v2
(`qa/make-decl-index.sh`, `qa/make-decl-index-v2.sh`; design: `feasibility/gpu-investigation.md` §4.1).

Outputs (next to this script, in research/qa/):
  decl-index-v3.tsv             gitignored. One row per declaration, LC_ALL=C sorted, no header:
                                  corpus  file  kind  name  qname  line  sha
                                name  = as written in the source, full dotted form (v2 cut it
                                        at the first '.'); structure fields and inductive
                                        constructors are rows too, named Parent.field
                                qname = name resolved against the enclosing `namespace`s
                                sha   = first 16 hex of sha256(kind, qname, statement, docstring)
                                kinds: theorem lemma def abbrev instance class structure
                                       inductive axiom opaque alias field ctor
  decl-index-v3-stmts.jsonl.gz  gitignored. The same records with the statement header text
                                (keyword up to the first top-level `:=` / `where`) and the
                                docstring. This is the text the semantic (embedding) stage reads.
  decl-index-v3-manifest.json   tracked. Corpus roots + git revs, counts, extractor version.
  decl-enrich-v3.tsv            tracked, curated: extra clues for declarations whose own names
                                are poor or uncommon (aliases, keywords, plain descriptions,
                                see-also links). A clue never edits a declaration; it adds
                                searchable text keyed by (corpus, qname), survives rebuilds, and
                                `enrich check` flags clues whose declaration changed or vanished.

Usage:
  python3 research/qa/decl_index_v3.py build                    # CPU only, a few minutes
  python3 research/qa/decl_index_v3.py find TERM...             # names + qnames + clues
  python3 research/qa/decl_index_v3.py find --stmts TERM...     # also statement + docstring text
  python3 research/qa/decl_index_v3.py enrich add CORPUS QNAME TYPE TEXT [--by WHO] [--both]
  python3 research/qa/decl_index_v3.py enrich check
  python3 research/qa/decl_index_v3.py coverage V2_TSV PROJ     # v2 rows not covered by v3
  cut -f4 research/qa/decl-index-v3.tsv | grep -xF 'NAME'       # v2-style exact-name check

Caveats (read before citing a result):
- Extraction is a comment-aware line scanner, not Lean elaboration. Names generated by Lean
  (auto-named instances, `to_additive`/`simps` outputs, structure projections' `mk`, ...)
  are not rows; anonymous instances appear as `[anonymous]`. Statement text is the header
  as written (cut at the first top-level `:=`/`where`, capped at 40 lines / 4000 chars).
- A miss is weak evidence of absence. A hit is never evidence of provability. Confirm every
  "corpus X has / lacks Y" claim with a direct-source `rg` in the tree (namespace check).
- Carried over from v2: openai-math vendors mathlib-like trees (also rg
  `openai-math/lean/OAI/`, `ComparatorChallenges/`, `preprints/` — preprints are never
  indexed); AxiomMath repos depend on mathlib, on TauCeti (dzzf copies TauCeti under
  `DedekindZetaZeroFree.TauCeti`) and on each other (ZetaZerosV2 carries a fork of
  ZetaZeros; PrimeNumberTheoremAnd embeds IEANTN/ and local Mathlib/ overrides; AreaLaw2D
  vendors openai-derived statements under OpenAI/), so same-name rows under several labels
  are expected; dzzf's vendor/ tree is indexed separately as axiommath-vendor-cft.
- Sibling repos are read-only; this script only reads them.
"""

