def cmd_embed_remap(a):
    """Re-point vector rows at decl ids after a db rebuild (sha is the stable key)."""
    import numpy as np
    vm, m = load_vec_manifest(), json.load(open(os.path.join(INDEX_DIR, MANIFEST_NAME), encoding="utf-8"))
    sha = np.load(vec_file("sha"))
    row_of = {int(s): i for i, s in enumerate(sha)}
    ids = np.full(len(sha), -1, dtype=np.int64)
    missing = 0
    seen = set()
    for did, s, *_ in scope_rows(open_db(), vm["scope_exclude"]):
        r = row_of.get(int(s, 16))
        if r is None:
            if s not in seen:
                missing += 1
                seen.add(s)
        elif ids[r] < 0:
            ids[r] = did
    np.save(vec_file("ids"), ids)
    vm["db_sha256"] = m["db_sha256"]
    vm["remap"] = {"orphan_vectors": int((ids < 0).sum()), "texts_without_vector": missing,
                   "utc": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")}
    with open(os.path.join(HERE, VEC_MANIFEST), "w", encoding="utf-8") as fh:
        json.dump(vm, fh, indent=1)
        fh.write("\n")
    print(f"-- remapped; {vm['remap']['orphan_vectors']} vectors without a declaration, {missing} "
          f"in-scope texts without a vector (embed them before relying on recall)", file=sys.stderr)


def cmd_embed_parity(a):
    """numpy encoder vs the GPU vectors (cosine) and vs the GPU tokenizer (token ids)."""
    import numpy as np
    from decl_embed import Encoder, blas_backend, warn_if_slow_blas
    warn_if_slow_blas(sys.stderr)
    vm = load_vec_manifest()
    V, ids = np.load(vec_file("f16"), mmap_mode="r"), np.load(vec_file("ids"))
    con = open_db()
    step = max(1, len(ids) // a.sample)
    rows = list(range(0, len(ids), step))[:a.sample]
    texts = []
    for r in rows:
        qn, st, dc = con.execute("SELECT qname, stmt, doc FROM decl_v WHERE id = ?", (int(ids[r]),)).fetchone()
        texts.append(embed_text(qn, st, dc))
    enc = Encoder()
    t0 = datetime.datetime.now()
    local = enc.encode(texts)
    secs = (datetime.datetime.now() - t0).total_seconds()
    cos = (local * V[rows].astype(np.float32)).sum(1)
    res = {"vectors": {"n": len(rows), "min_cos": float(cos.min()), "mean_cos": float(cos.mean()),
                       "local_encode_s_per_text": round(secs / len(rows), 4), "blas": blas_backend(),
                       "python": sys.executable}}
    if a.tok_sample:
        sample = json.load(open(a.tok_sample, encoding="utf-8"))
        tex = {}
        import gzip
        want = {int(k) for k in sample}
        with gzip.open(a.texts, "rt", encoding="utf-8") as fh:
            for i, line in enumerate(fh):
                if i in want:
                    tex[i] = line.rstrip("\n").split("\t", 1)[1]
        bad = [i for i in want if enc.tok.encode(tex[i]) != sample[str(i)]]
        res["tokens"] = {"n": len(want), "mismatches": len(bad), "examples": sorted(bad)[:5]}
    vm["parity"] = res
    with open(os.path.join(HERE, VEC_MANIFEST), "w", encoding="utf-8") as fh:
        json.dump(vm, fh, indent=1)
        fh.write("\n")
    print(json.dumps(res, indent=1))
    ok = res["vectors"]["min_cos"] >= 0.999 and res.get("tokens", {}).get("mismatches", 0) == 0
    sys.exit(0 if ok else 1)


def semantic_find(a, con, corpora, clues_by_key, enrich):
    import numpy as np
    from decl_embed import Encoder, QUERY_INSTRUCTION, warn_if_slow_blas
    warn_if_slow_blas(sys.stderr)
    vm = load_vec_manifest()
    m = json.load(open(os.path.join(INDEX_DIR, MANIFEST_NAME), encoding="utf-8"))
    if vm["db_sha256"] != m["db_sha256"]:
        print("WARN: vectors were mapped against another db build — run `embed remap`", file=sys.stderr)
    V = np.load(vec_file("f16"), mmap_mode="r")
    sha_arr, ids = np.load(vec_file("sha")), np.load(vec_file("ids"))
    enc = Encoder()
    exclude_sha = None
    if a.like:
        target = name_lookup(con, " ".join(a.terms))
        if not target:
            sys.exit(f"--like: no declaration named {' '.join(a.terms)!r}")
        tsha = int(target[0][5], 16)
        hit = np.nonzero(sha_arr == tsha)[0]
        if len(hit):
            qv = V[hit[0]].astype(np.float32)
        else:  # outside the embedded scope (e.g. openai-math): encode it here
            qn, st, dc = con.execute("SELECT qname, stmt, doc FROM decl_v WHERE sha = ? LIMIT 1",
                                     (target[0][5],)).fetchone()
            qv = enc.encode([embed_text(qn, st, dc)])[0]
        exclude_sha = tsha
        print(f"-- nearest to {target[0][0]}:{target[0][4]}", file=sys.stderr)
    else:
        qv = enc.encode([("" if a.raw_query else QUERY_INSTRUCTION) + query_text(" ".join(a.terms))])[0]
    scores = np.empty(len(V), dtype=np.float32)
    for i in range(0, len(V), 65536):
        scores[i:i + 65536] = V[i:i + 65536].astype(np.float32) @ qv
    if exclude_sha is not None:
        scores[sha_arr == exclude_sha] = -2.0
    k = min(len(scores), a.limit * (8 if corpora else 2) + 8)
    top = np.argpartition(-scores, k - 1)[:k]
    top = top[np.argsort(-scores[top])]
    hits = []
    for r in top:
        if ids[r] < 0:
            continue
        row = con.execute(f"{ROW_SQL} WHERE d.id = ?", (int(ids[r]),)).fetchone()
        if row and (not corpora or row[0] in corpora):
            hits.append((float(scores[r]), row, "cos"))
    if enrich and not a.like:  # clues are extra entry points: embedded on the fly, few of them
        cv = enc.encode([words(r["text"], ascii_ops=False) for r in enrich])
        floor = hits[min(len(hits), a.limit) - 1][0] if hits else -1.0
        for r, s in zip(enrich, cv @ qv):
            if s >= floor and (not corpora or r["corpus"] in corpora):
                for row in name_lookup(con, r["qname"], corpus=r["corpus"], by="qname"):
                    hits.append((float(s), row, f"via clue {r['type']}"))
    best = {}
    for s, row, tag in hits:
        key = (row[0], row[1], row[2], row[4])
        if key not in best or s > best[key][0]:
            best[key] = (s, row, tag)
    ranked = sorted(best.values(), key=lambda x: -x[0])[:a.limit]
    for s, row, tag in ranked:
        print_row(row, f"{tag} {s:.3f}", clues_by_key)
    print(f"-- semantic: {len(V)} vectors ({vm['model']}, scope excludes {vm['scope_exclude'] or 'nothing'}); "
          f"showing {len(ranked)}", file=sys.stderr)


def cmd_coverage(a):
    """v2 rows with no v3 projection (v3 names cut the way v2's regex cut them)."""
    tmp = tempfile.mkdtemp(prefix=".decl-v3-tmp-cov-", dir=HERE)
    env = dict(os.environ, LC_ALL="C")
    s2, s3 = os.path.join(tmp, "v2.s"), os.path.join(tmp, "v3proj.s")
    subprocess.run(["sort", "-u", "-S", "256M", "-T", tmp, "-o", s2, a.v2], env=env, check=True)
    subprocess.run(["sort", "-u", "-S", "256M", "-T", tmp, "-o", s3, a.proj], env=env, check=True)
    with open(a.out, "w", encoding="utf-8") as fh:
        subprocess.run(["comm", "-23", s2, s3], env=env, check=True, stdout=fh)
    for p in (s2, s3):
        os.remove(p)
    os.rmdir(tmp)
    # Classify each uncovered v2 row by re-reading its source line(s):
    #   in-comment    every line v2 matched lies inside a comment/docstring (v2 false positive)
    #   not-in-source no line matches any more (file changed since v2 was built)
    #   UNEXPLAINED   a live code line matches but v3 has no row — a v3 extractor miss
    roots = {label: root for label, root, _ in CORPORA}
    cache, counts, rows = {}, {}, []
    with open(a.out, encoding="utf-8") as fh:
        for line in fh:
            corpus, rel, kind, name = line.rstrip("\n").split("\t")
            path = os.path.join(roots.get(corpus, ""), rel)
            if path not in cache:
                try:
                    with open(path, encoding="utf-8", errors="replace") as src:
                        lines = src.read().split("\n")
                    cache = {path: (lines, split_code(lines)[0])}
                except OSError:
                    cache = {path: ([], [])}
            lines, code = cache[path]
            pat = re.compile(rf"^{kind}\s+{re.escape(name)}(?![A-Za-z0-9_!?'])")
            hits = [i for i, l in enumerate(lines) if pat.match(l)]
            cls = ("not-in-source" if not hits else
                   "in-comment" if not any(pat.match(code[i]) for i in hits) else "UNEXPLAINED")
            counts[(corpus, cls)] = counts.get((corpus, cls), 0) + 1
            rows.append(f"{corpus}\t{rel}\t{kind}\t{name}\t{cls}\t{','.join(str(i + 1) for i in hits[:5])}")
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write("".join(r + "\n" for r in rows))
    for (c, cls), k in sorted(counts.items(), key=lambda x: (x[0][1], -x[1])):
        print(f"{k}\t{c}\t{cls}")
    print(f"-- {len(rows)} v2 rows not covered (corpus file kind name class lines) -> {a.out}",
          file=sys.stderr)


