def cmd_build(a):
    only = set(a.only.split(",")) if a.only else None
    if only and not a.out_dir:
        sys.exit("--only builds a partial index; give --out-dir so research/qa/ is not overwritten")
    out_dir = a.out_dir or HERE
    os.makedirs(out_dir, exist_ok=True)
    final = os.path.join(out_dir, DB_NAME)
    # Build into a temp file next to the output (disk, not the small RAM-backed /tmp) and
    # point SQLite's own temp files (index sorts) there too. Pattern `.decl-v3-tmp-*` is ignored.
    tmp_db = os.path.join(out_dir, ".decl-v3-tmp-build.sqlite")
    if os.path.exists(tmp_db):
        os.remove(tmp_db)
    os.environ["SQLITE_TMPDIR"] = out_dir
    started = datetime.datetime.now(datetime.timezone.utc)
    con = sqlite3.connect(tmp_db)
    con.executescript("PRAGMA journal_mode=OFF; PRAGMA synchronous=OFF; PRAGMA page_size=8192;"
                      "PRAGMA cache_size=-262144;" + SCHEMA)
    corpora_info, decl_id, file_id, ns_ids = [], 0, 0, {}
    with Pool(a.jobs) as pool, \
            (open(a.proj, "w", encoding="utf-8") if a.proj else open(os.devnull, "w")) as fp:
        for label, root, excl in CORPORA:
            if only and label not in only:
                continue
            if not os.path.isdir(root):
                print(f"WARN: root missing for {label}: {root} (skipped)", file=sys.stderr)
                continue
            gi = git_info(root)
            cid = len(corpora_info) + 1
            con.execute("INSERT INTO corpus VALUES (?,?,?,?)", (cid, label, root, gi["rev"]))
            files = list_files(root, excl)
            kinds = {}
            # Batches bound the results buffered in this process when workers outrun the writer.
            for b0 in range(0, len(files), 1024):
                batch = [(label, root, f, bool(a.proj)) for f in files[b0:b0 + 1024]]
                frows, nrows, drows, trows = [], [], [], []
                for _, rel, recs, proj in pool.imap(parse_file, batch, chunksize=16):
                    if proj:
                        fp.write("".join(r + "\n" for r in proj))
                    if not recs:
                        continue
                    file_id += 1
                    frows.append((file_id, cid, rel))
                    for kind, name, prefix, line, sha, stmt, doc, wn, ws, wd in recs:
                        decl_id += 1
                        kinds[kind] = kinds.get(kind, 0) + 1
                        nid = ns_ids.get(prefix)
                        if nid is None:
                            nid = ns_ids[prefix] = len(ns_ids) + 1
                            nrows.append((nid, prefix))
                        drows.append((decl_id, file_id, nid, kind, name, line, sha, stmt, doc))
                        trows.append((decl_id, wn, ws, wd))
                con.executemany("INSERT INTO file VALUES (?,?,?)", frows)
                con.executemany("INSERT INTO ns VALUES (?,?)", nrows)
                con.executemany("INSERT INTO decl VALUES (?,?,?,?,?,?,?,?,?)", drows)
                con.executemany("INSERT INTO decl_fts(rowid, name_words, stmt_words, doc_words) "
                                "VALUES (?,?,?,?)", trows)
                con.commit()
            n = sum(kinds.values())
            corpora_info.append({"label": label, "root": root, "exclude": excl, **gi,
                                 "files": len(files), "records": n,
                                 "by_kind": dict(sorted(kinds.items()))})
            print(f"scanned {label}: {len(files)} files, {n} records", file=sys.stderr)
    print("optimizing the full-text index ...", file=sys.stderr)
    con.execute("INSERT INTO decl_fts(decl_fts) VALUES ('optimize')")
    con.commit()
    con.execute("ANALYZE")
    con.commit()
    con.close()
    os.replace(tmp_db, final)
    manifest = {
        "index": "decl-index-v3", "extractor": VERSION, "words": WORDS_VERSION,
        "script": "research/qa/decl_index_v3.py",
        "built_utc": started.strftime("%Y-%m-%dT%H:%M:%SZ"), "partial": sorted(only) if only else None,
        "db": DB_NAME, "db_bytes": os.path.getsize(final), "db_sha256": sha256_file(final),
        "rows": decl_id, "files_with_decls": file_id, "namespaces": len(ns_ids),
        "tables": "corpus(id,label,root,rev) file(id,corpus_id,path) ns(id,ns) "
                  "decl(id,file_id,ns_id,kind,name,line,sha,stmt,doc) "
                  "view decl_v(id,file_id,kind,name,qname,line,sha,stmt,doc) "
                  "decl_fts(name_words,stmt_words,doc_words; contentless, "
                  "porter unicode61, rowid=decl.id)",
        "corpora": corpora_info,
        "enrichment": "research/qa/decl-enrich-v3.tsv (keyed by corpus+qname; see `enrich check`)",
    }
    with open(os.path.join(out_dir, MANIFEST_NAME), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    print(f"total: {decl_id} rows -> {final} ({manifest['db_bytes'] / 1e6:.0f} MB)", file=sys.stderr)


