ATOM = r"(?:«[^»\n]*»|[^\W\d][\w'!?]*)"
IDENT = rf"{ATOM}(?:\.(?:{ATOM}|\d+))*"
IDENT_RE = re.compile(IDENT)
ATOM_RE = re.compile(ATOM)
MODS = r"(?:(?:private|protected|noncomputable|partial|unsafe|nonrec|scoped|local|public|meta)\s+)*"
DECL_RE = re.compile(
    rf"^{MODS}(theorem|lemma|def|abbrev|instance|class\s+inductive|class|structure|inductive"
    rf"|axiom|opaque|irreducible_def|alias|example)\b\s*(.*)$")
NS_RE = re.compile(rf"^namespace\s+({IDENT})")
SEC_RE = re.compile(r"^(?:(?:noncomputable|public|private|meta)\s+)*section\b")
MUTUAL_RE = re.compile(r"^mutual\b")
END_RE = re.compile(r"^end\b")
PREFIX_IN_RE = re.compile(r"^(?:open|set_option|omit|include|unseal|attribute|variable)\b.*?\sin\b\s*")
FIELD_RE = re.compile(rf"^((?:{ATOM}\s+)*?{ATOM})\s*(?::|\(|\{{|\[|⦃)")
CTORNAME_RE = re.compile(rf"^{ATOM}\s*::")
CTOR_RE = re.compile(rf"^\|\s*({ATOM})")
BODY_SKIP_RE = re.compile(r"^(?:extends|deriving|where)\b")
# v2's name pattern, used only to project v3 rows onto v2 rows for the coverage check.
V2NAME_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_!?']*")
V2KINDS = {"theorem", "lemma", "def", "abbrev", "instance", "class", "structure", "inductive", "axiom"}
OPEN = set("([{⟨⦃⟦⁅")
CLOSE = set(")]}⟩⦄⟧⁆")


def norm(text):
    return " ".join(text.split())


def split_code(lines):
    """Strip comments. Returns (code lines, docstring text closing on each line or None)."""
    code, docs = [], [None] * len(lines)
    depth, doc = 0, None
    for idx, line in enumerate(lines):
        if depth == 0 and "-" not in line:
            code.append(line)
            continue
        out, i, n = [], 0, len(line)
        while i < n:
            if depth > 0:
                jo, jc = line.find("/-", i), line.find("-/", i)
                if jc == -1 and jo == -1:
                    if doc is not None and depth == 1:
                        doc.append(line[i:])
                    break
                if jo != -1 and (jc == -1 or jo < jc):
                    if doc is not None and depth == 1:
                        doc.append(line[i:jo])
                    depth += 1
                    i = jo + 2
                else:
                    if doc is not None and depth == 1:
                        doc.append(line[i:jc])
                        docs[idx] = " ".join(doc)
                        doc = None
                    depth -= 1
                    i = jc + 2
            else:
                jb, jl = line.find("/-", i), line.find("--", i)
                if jl != -1 and (jb == -1 or jl < jb):
                    out.append(line[i:jl])
                    break
                if jb == -1:
                    out.append(line[i:])
                    break
                out.append(line[i:jb])
                depth = 1
                if line.startswith("/--", jb) and not line.startswith("/--/", jb):
                    doc, i = [], jb + 3
                else:
                    doc, i = None, jb + 2
        code.append("".join(out))
    return code, docs


def strip_attrs(s, depth):
    """Remove leading @[...] groups (possibly continued from earlier lines)."""
    i, n = 0, len(s)
    while True:
        if depth == 0:
            while i < n and s[i].isspace():
                i += 1
            if not s.startswith("@[", i):
                return s[i:], 0
            depth, i = 1, i + 2
        while i < n and depth > 0:
            c = s[i]
            if c == "[":
                depth += 1
            elif c == "]":
                depth -= 1
            i += 1
        if depth > 0:
            return "", depth


def find_term(text, depth, stop_where=True):
    """First top-level ':=' (or 'where'). Returns (pos, terminator, depth)."""
    n = len(text)
    for i, c in enumerate(text):
        if c in OPEN:
            depth += 1
        elif c in CLOSE:
            if depth > 0:
                depth -= 1
        elif depth == 0:
            if c == ":" and i + 1 < n and text[i + 1] == "=":
                return i, ":=", depth
            if (c == "w" and stop_where and text.startswith("where", i)
                    and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] in "_'."))
                    and (i + 5 == n or not (text[i + 5].isalnum() or text[i + 5] in "_'"))):
                return i, "where", depth
    return -1, None, depth


def capture(code, i, first):
    """Statement header from line i: up to the first top-level ':='/'where', a blank or
    dedented line, or a '| ' match-arm line. Returns (text, last line index, terminator, rest)."""
    n, parts, depth, j, text, total = len(code), [], 0, i, first, 0
    while True:
        pos, term, depth = find_term(text, depth)
        if term is not None:
            parts.append(text[:pos])
            return norm(" ".join(parts)), j, term, text[pos + (2 if term == ":=" else 5):]
        parts.append(text)
        total += len(text)
        if j - i + 1 >= 40 or total >= 4000:
            return norm(" ".join(parts)), j, "limit", ""
        if j + 1 >= n:
            return norm(" ".join(parts)), j, "eof", ""
        nxt = code[j + 1]
        s = nxt.strip()
        if not s:
            return norm(" ".join(parts)), j, "blank", ""
        if not nxt[0].isspace():
            return norm(" ".join(parts)), j, "dedent", ""
        if s == "|" or s.startswith("| "):
            return norm(" ".join(parts)), j, "bar", ""
        j += 1
        text = nxt


def cut_assign(text):
    pos, term, _ = find_term(text, 0, stop_where=False)
    return text[:pos] if term == ":=" else text


def parse_fields(lines, code, docs, k):
    """Fields of a structure/class body starting at line k. Ends at the first non-blank
    source line in column 0."""
    n, fields, findent, cur, pending = len(code), [], None, None, None
    while k < n:
        raw = lines[k]
        if raw.strip() and not raw[0].isspace():
            break
        if docs[k] is not None:
            pending = docs[k]
        c = code[k]
        s = c.strip()
        if not s:
            k += 1
            continue
        ind = len(c) - len(c.lstrip())
        if cur is not None and ind > findent:
            cur[1].append(s)
            k += 1
            continue
        s2 = re.sub(r"^(?:protected|private)\s+", "", s)
        m = None
        if not (CTORNAME_RE.match(s2) or BODY_SKIP_RE.match(s2) or s2.startswith(("|", "@["))):
            m = FIELD_RE.match(s2)
        if m:
            findent = ind
            cur = [m.group(1).split(), [s2], pending, k + 1]
            fields.append(cur)
        else:
            cur = None
        pending = None
        k += 1
    return fields, k


def parse_ctors(lines, code, docs, k, after):
    """Constructors of an inductive: '| name ...' lines from line k (column 0 allowed)."""
    ctors, cur, pending = [], None, None
    for seg in after.split("|")[1:]:
        mm = ATOM_RE.match(seg.strip())
        if mm:
            ctors.append([mm.group(0), ["| " + seg.strip()], None, k])
    n = len(code)
    while k < n:
        raw = lines[k]
        if raw.strip() and not raw[0].isspace() and not raw.startswith("|"):
            break
        if docs[k] is not None:
            pending = docs[k]
        s = code[k].strip()
        if not s:
            k += 1
            continue
        if s.startswith("|"):
            mm = CTOR_RE.match(s)
            cur = [mm.group(1), [s], pending, k + 1] if mm else None
            if cur:
                ctors.append(cur)
            pending = None
        elif s.startswith("deriving"):
            cur = None
        elif cur is not None:
            cur[1].append(s)
        k += 1
    return ctors, k


def qualify(prefix, name):
    if name.startswith("_root_."):
        return name[7:]
    return f"{prefix}.{name}" if prefix else name


def parse_alias(rest):
    rest = rest.strip()
    if rest.startswith("⟨"):
        inner = rest[1:rest.find("⟩")] if "⟩" in rest else rest[1:]
        return [x.strip() for x in inner.split(",") if x.strip() and x.strip() != "_"]
    mm = IDENT_RE.match(rest)
    return [mm.group(0)] if mm else []


def skip_priority(r):
    if not r.startswith("(priority"):
        return r
    depth = 0
    for i, c in enumerate(r):
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return r[i + 1:].lstrip()
    return r


def parse_file(task):
    corpus, root, rel, want_proj = task
    try:
        with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as fh:
            lines = fh.read().split("\n")
    except OSError:
        return [], [], []
    code, docs = split_code(lines)
    tsv, js, proj = [], [], []
    stack, pending, attr, i, n = [], None, 0, 0, len(code)

    def emit(kind, name, line, stmt, doc):
        prefix = ".".join(x for x in stack if x)
        qname = qualify(prefix, name)
        doc = norm(doc)[:1500] if doc else ""
        sha = hashlib.sha256("\x1f".join((kind, qname, stmt, doc)).encode()).hexdigest()[:16]
        tsv.append("\t".join((corpus, rel, kind, name, qname, str(line), sha)))
        js.append(json.dumps({"corpus": corpus, "file": rel, "line": line, "kind": kind,
                              "name": name, "qname": qname, "stmt": stmt, "doc": doc,
                              "sha": sha}, ensure_ascii=False))

    while i < n:
        if docs[i] is not None:
            pending = docs[i]
        s = code[i].strip()
        if not s:
            i += 1
            continue
        if attr > 0 or s.startswith("@["):
            s, attr = strip_attrs(s, attr)
            if not s:
                i += 1
                continue
        m = PREFIX_IN_RE.match(s)
        while m:
            s = s[m.end():]
            m = PREFIX_IN_RE.match(s)
        if not s:
            i += 1
            continue
        m = NS_RE.match(s)
        if m:
            stack.append(m.group(1))
            pending, i = None, i + 1
            continue
        if SEC_RE.match(s) or MUTUAL_RE.match(s):
            stack.append(None)
            pending, i = None, i + 1
            continue
        if END_RE.match(s):
            if stack:
                stack.pop()
            pending, i = None, i + 1
            continue
        m = DECL_RE.match(s)
        if not m:
            pending, i = None, i + 1
            continue
        kw, rest = " ".join(m.group(1).split()), m.group(2)
        line = i + 1
        if kw == "example":
            _, j_end, _, _ = capture(code, i, s)
            pending, i = None, j_end + 1
            continue
        if kw == "alias":
            text, j = ["alias " + rest], i + 1
            while j < n and j - i <= 4 and code[j].strip() and code[j][0].isspace():
                text.append(code[j])  # alias target continued on indented lines
                j += 1
            for nm in parse_alias(rest):
                emit("alias", nm, line, norm(" ".join(text)), pending)
            pending, i = None, j
            continue
        kind = {"class inductive": "class", "irreducible_def": "def"}.get(kw, kw)
        if kind == "instance":
            r2 = skip_priority(rest)
            mm = IDENT_RE.match(r2)
            name = mm.group(0) if mm else "[anonymous]"
        else:
            mm = IDENT_RE.match(rest)
            if not mm:
                pending, i = None, i + 1
                continue
            name = mm.group(0)
        stmt, j_end, term, after = capture(code, i, s[m.start(1):])
        emit(kind, name, line, stmt, pending)
        if want_proj:
            if kw == "class inductive":
                proj.append(f"{corpus}\t{rel}\tclass\tinductive")
            elif kw in V2KINDS:
                pm = V2NAME_RE.match(name)
                if pm:
                    proj.append(f"{corpus}\t{rel}\t{kw}\t{pm.group(0)}")
        pending = None
        if kind in ("structure", "class") and kw != "class inductive" and term == "where":
            fields, i = parse_fields(lines, code, docs, j_end + 1)
            for names, parts, fdoc, fline in fields:
                ftext = norm(cut_assign(" ".join(parts)))
                for fn in names:
                    emit("field", f"{name}.{fn}", fline, ftext, fdoc)
            continue
        if kind == "inductive" or kw == "class inductive":
            ctors, i = parse_ctors(lines, code, docs, j_end + 1, after if term == "where" else "")
            for cn, parts, cdoc, cline in ctors:
                emit("ctor", f"{name}.{cn}", cline, norm(" ".join(parts)), cdoc)
            continue
        i = j_end + 1
    return tsv, js, proj


def list_files(root, excl):
    args = ["rg", "--files", "-g", "*.lean"] + (["-g", excl] if excl else [])
    out = subprocess.run(args, cwd=root, capture_output=True, text=True).stdout
    return sorted(p[2:] if p.startswith("./") else p for p in out.splitlines() if p)


def git_info(root):
    def g(*a):
        r = subprocess.run(["git", "-C", root, *a], capture_output=True, text=True)
        return r.stdout.strip() if r.returncode == 0 else None
    return {"rev": g("rev-parse", "HEAD"), "commit_date": g("log", "-1", "--format=%cI")}


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def cmd_build(a):
    only = set(a.only.split(",")) if a.only else None
    if only and not a.out_dir:
        sys.exit("--only builds a partial index; give --out-dir so research/qa/ is not overwritten")
    out_dir = a.out_dir or HERE
    os.makedirs(out_dir, exist_ok=True)
    tsv_path = os.path.join(out_dir, TSV_NAME)
    stmts_path = os.path.join(out_dir, STMTS_NAME)
    # Temp files go next to the outputs (disk), not $TMPDIR: /tmp is a small RAM-backed tmpfs
    # here and the unsorted TSV alone is ~0.8 GB. Pattern `.decl-v3-tmp-*` is gitignored.
    tmp = tempfile.mkdtemp(prefix=".decl-v3-tmp-", dir=out_dir)
    raw_tsv = os.path.join(tmp, "raw.tsv")
    started = datetime.datetime.now(datetime.timezone.utc)
    corpora_info, total = [], 0
    with open(raw_tsv, "w", encoding="utf-8") as ft, \
            gzip.open(stmts_path, "wt", encoding="utf-8", compresslevel=3) as fj, \
            (open(a.proj, "w", encoding="utf-8") if a.proj else open(os.devnull, "w")) as fp, \
            Pool(a.jobs) as pool:
        for label, root, excl in CORPORA:
            if only and label not in only:
                continue
            if not os.path.isdir(root):
                print(f"WARN: root missing for {label}: {root} (skipped)", file=sys.stderr)
                continue
            files = list_files(root, excl)
            kinds = {}
            # Batches bound the results buffered in this process when workers outrun the
            # writer (one unbatched imap over openai-math peaked at ~1.5 GB RSS).
            for b0 in range(0, len(files), 1024):
                batch = [(label, root, f, bool(a.proj)) for f in files[b0:b0 + 1024]]
                for tsv, js, proj in pool.imap(parse_file, batch, chunksize=16):
                    for row in tsv:
                        k = row.split("\t", 3)[2]
                        kinds[k] = kinds.get(k, 0) + 1
                    ft.write("".join(r + "\n" for r in tsv))
                    fj.write("".join(r + "\n" for r in js))
                    fp.write("".join(r + "\n" for r in proj))
            n = sum(kinds.values())
            total += n
            corpora_info.append({"label": label, "root": root, "exclude": excl, **git_info(root),
                                 "files": len(files), "records": n,
                                 "by_kind": dict(sorted(kinds.items()))})
            print(f"scanned {label}: {len(files)} files, {n} records", file=sys.stderr)
    env = dict(os.environ, LC_ALL="C")
    subprocess.run(["sort", "-u", "-S", "256M", "-T", tmp, "-o", tsv_path, raw_tsv], env=env, check=True)
    os.remove(raw_tsv)
    os.rmdir(tmp)
    with open(tsv_path, encoding="utf-8") as fh:
        rows = sum(1 for _ in fh)
    manifest = {
        "index": "decl-index-v3", "extractor": VERSION, "script": "research/qa/decl_index_v3.py",
        "built_utc": started.strftime("%Y-%m-%dT%H:%M:%SZ"), "partial": sorted(only) if only else None,
        "tsv_columns": TSV_COLS, "tsv_rows": rows, "tsv_sha256": sha256_file(tsv_path),
        "stmts_records": total, "corpora": corpora_info,
        "enrichment": "research/qa/decl-enrich-v3.tsv (keyed by corpus+qname; see `enrich check`)",
    }
    with open(os.path.join(out_dir, MANIFEST_NAME), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    print(f"total: {rows} rows -> {tsv_path}", file=sys.stderr)


