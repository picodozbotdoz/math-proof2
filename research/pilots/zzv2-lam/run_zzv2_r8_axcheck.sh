#!/bin/bash
# zzv2-lam eta-R8 FULL-COVERAGE axcheck on Modal (app crossmath-pilot-zzv2-lam-r8-axcheck;
# the grant run 2 = the R8 EXIT CRITERION): the run_zzv2_r8 mechanism over the APPENDUM'd
# eta-r8 copy = fired bytes + a generated #print-axioms census of EVERY top-level decl
# (pilot-10 axcheck_full pattern; the repo file is untouched). Chain modules re-compile
# with -o so THEIR in-file gates re-fire too. MODAL_USER=doz. The al3d one-liners bind.
#
#   research/pilots/zzv2-lam/run_zzv2_r8_axcheck.sh
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
STAGE=/tmp/crossmath-zzv2-r8-axcheck-stage
MODAL_USER=${MODAL_USER:-doz}
MODAL_BIN=/home/doz/dozenv/bin/modal

rm -rf "$STAGE"; mkdir -p "$STAGE"
cp "$HERE"/run_zzv2_r8_axcheck.py "$STAGE"/
cp "$HERE"/P1.lean "$STAGE"/ZZLamP1.lean
cp "$HERE"/eta-r3.lean "$STAGE"/EtaR3.lean

# The appendum (generated census; assertion-guarded): every top-level theorem/def of
# eta-r8.lean gets a #print axioms line appended to the staged copy.
python3 - "$HERE/eta-r8.lean" "$STAGE/eta-r8.lean" <<'EOF'
import re, sys
src, dst = sys.argv[1], sys.argv[2]
text = open(src).read()
names = re.findall(r'^(?:noncomputable def|def|theorem|private theorem)\s+([A-Za-z_][A-Za-z0-9_\'!?]*|([^ \n]+))', text, re.M)
# simpler: line-start decl matcher over the file body (the family census class)
census = []
for line in text.splitlines():
    m = re.match(r'^(?:noncomputable def|def|theorem)\s+([A-Za-z_][A-Za-z0-9_\'!?]*)', line)
    if m:
        census.append(m.group(1))
assert census, "census EMPTY - refusing to stage"
appendum = ["\n-- APPENDUM (generated by run_zzv2_r8_axcheck.sh; the pilot-10 full-coverage",
            "-- census of this file's top-level publics; repo file untouched):"]
for n in census:
    appendum.append(f"#print axioms ZZLam.EtaPort.{n}")
open(dst, "w").write(text + "\n".join(appendum) + "\n")
print(f"[axcheck-stage] census: {census}")
EOF

chmod -R a+rX "$STAGE"

cd "$STAGE" && "$MODAL_BIN" run run_zzv2_r8_axcheck.py --dir "$STAGE" \
  --root /home/doz/zcode-workdir/axiommath
