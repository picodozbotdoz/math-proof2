#!/usr/bin/env python3
"""One-shot generator for the RHLinalg port prefixes (milestone (b)).

Donor: /home/doz/zcode-workdir/anthropics_formal-math/zeta23/Zeta23/ (read-only).
Emits research/pilots/01/port/{01..08}_*.lean: file k = tailored import header +
verbatim concatenation of donor bodies 1..k (each donor file stripped of its leading
copyright/provenance comments and its import lines; EVERYTHING ELSE KEPT VERBATIM —
proofs included). Prefix = self-contained module compiled against mathlib oleans only;
the prefix chain realizes the topo order of blueprint §1 (umbrella LinAlg.lean is
subsumed by 07_RankTrace = the whole namespace; TightMult excluded per blueprint).

Name-pin corrections applied via the tailored headers (blueprint §6):
  + Mathlib.Analysis.Convex.DoublyStochasticMatrix (reindex_mem_doublyStochastic, VonNeumann)
  + Mathlib.Analysis.Matrix.Spectrum, Mathlib.Algebra.Star.Unitary{,StarAlgAut}
  + Mathlib.LinearAlgebra.Dimension.Finrank (finrank_range_of_inj, Sylvester)
Run once; afterwards the generated files are hand-maintained (fix cycles edit them directly).
"""
import pathlib, re, sys

DONOR = pathlib.Path("/home/doz/zcode-workdir/anthropics_formal-math/zeta23/Zeta23")
OUT = pathlib.Path("/home/doz/zcode-workdir/cross-math-fronttier/research/pilots/01/port")
OUT.mkdir(parents=True, exist_ok=True)

# (output name, donor relpath, extra imports needed by this prefix)
CHAIN = [
    ("01_PosIndex.lean",        "LinAlg/PosIndex.lean",        ["Mathlib.Analysis.Matrix.Spectrum"]),
    ("02_HermitianPosPart.lean","LinAlg/HermitianPosPart.lean",[]),
    ("03_VonNeumann.lean",      "LinAlg/VonNeumann.lean",      ["Mathlib.Analysis.Convex.Birkhoff",
                                                               "Mathlib.Analysis.Convex.DoublyStochasticMatrix",
                                                               "Mathlib.Algebra.Order.Rearrangement",
                                                               "Mathlib.Algebra.Star.Unitary",
                                                               "Mathlib.Algebra.Star.UnitaryStarAlgAut"]),
    ("04_Sylvester.lean",       "LinAlg/Sylvester.lean",       ["Mathlib.LinearAlgebra.Dimension.Finrank",
                                                               "Mathlib.LinearAlgebra.FiniteDimensional.Lemmas"]),
    ("05_Inertia.lean",         "LinAlg/Inertia.lean",         []),
    ("06_Weyl.lean",            "LinAlg/Weyl.lean",            ["Mathlib.Algebra.Order.Chebyshev"]),
    ("07_RankTrace.lean",       "LinAlg/RankTrace.lean",       []),
    ("08_RankTraceMult.lean",   "ZeroSide/RankTraceMult.lean", ["Mathlib.LinearAlgebra.Lagrange"]),
]
BASE_IMPORTS = ["Mathlib.Analysis.Matrix.PosDef"]

def body(path: pathlib.Path) -> str:
    lines = path.read_text().splitlines()
    last_import = max(i for i, l in enumerate(lines) if l.startswith("import "))
    return "\n".join(lines[last_import + 1:]).strip("\n")

HEADER = """/-
Milestone (b) port prefix — cross-math-fronttier pilot 01 (dossier 01/03 shared port).
Generated by research/pilots/01/make_port.py from the read-only zeta23 donor; bodies are
VERBATIM donor text (copyright Anthropic, PBC; Apache 2.0 — see donor repo), only the
per-file headers/imports were folded into one tailored header. This prefix contains:
{contains}
Compile target: mathlib v4.36.0-rc2 @ ff2494ea (Modal, crossmath-probe pattern).
-/
"""

def imports_for(extras):
    all_imports = BASE_IMPORTS + list(dict.fromkeys(extras))
    return "\n".join(f"import {m}" for m in all_imports)

bodies, names, acc = [], [], []
for out_name, rel, extras in CHAIN:
    b = body(DONOR / rel)
    bodies.append(b)
    acc.append(rel)
    content = (HEADER.format(contains=" + ".join(acc)) + imports_for(
        [e for _, _, ex in CHAIN[:CHAIN.index((out_name, rel, extras)) + 1] for e in ex])
        + "\n\n" + "\n\n".join(bodies) + "\n")
    (OUT / out_name).write_text(content)
    names.append(out_name)
    print(f"{out_name}: {len(content.splitlines())} LoC (cumulative)")
print("done:", ", ".join(names))
